// Pre-compiles the case v1 JSON Schema into a standalone validator function
// at build time, so the browser never needs to eval/new-Function a schema at
// runtime -- required because the site's CSP is script-src 'self' (no
// unsafe-eval). See src/lib/validateCase.ts.
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "..");
const SCHEMA_PATH = resolve(REPO_ROOT, "contract/schema/case.v1.schema.json");
const OUT_PATH = resolve(REPO_ROOT, "src/lib/generated/caseValidator.js");

const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf-8"));

// unicode: false skips ajv's ucs2length runtime helper for min/maxLength
// (plain .length instead) -- that helper is pulled in via a bare require()
// that standalone/esm mode doesn't convert to an import, which breaks in
// the browser. Case content is plain-authored text, not user input that
// needs exact astral-plane-character-aware length limits.
const ajv = new Ajv2020({ allErrors: true, strict: false, unicode: false, code: { source: true, esm: true } });
// Only the "date" format is used in the schema. Register it as a plain
// regex (not the full ajv-formats package) so the standalone-compiled
// output is self-contained -- ajv-formats' fuller format functions pull in
// a runtime helper module via require(), which the browser can't resolve
// and which the CSP (script-src 'self', no unsafe-eval) can't work around.
ajv.addFormat("date", /^\d{4}-\d{2}-\d{2}$/);

const validate = ajv.compile(schema);
const moduleCode = standaloneCode(ajv, validate);

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(
  OUT_PATH,
  `// AUTO-GENERATED by scripts/generate-case-validator.mjs from contract/schema/case.v1.schema.json.\n// Do not edit by hand -- this runs as part of \`npm run build\`.\n${moduleCode}`
);

console.log(`Generated ${OUT_PATH}`);
